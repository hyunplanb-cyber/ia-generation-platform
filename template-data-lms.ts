// 서비스 생성 스키마와 동일한 구조. 상태별 화면 분리 · 화면별 프롬프트 포함.

export interface TplScreen {
  ref: string;
  name: string;
  role: string;
  func: string;
  prompt: string;
  /** 눌렀을 때 다른 화면으로 가는 것 — [버튼 이름, 갈 화면 ref] */
  btns?: [string, string][];
  /**
   * 눌렀을 때 이 화면 안에서 끝나는 것 — [무엇을 누르면, 무엇이 바뀐다]
   *
   * 이 칸이 없던 동안, 스펙팩이 버튼에 대해 적을 수 있는 것은 "어느 화면으로
   * 가는가" 하나뿐이었다. 그래서 만들어진 사이트는 눌러도 값이 안 바뀌는
   * 포스터가 됐다. 우리가 안 시킨 것을 AI 가 알아서 해 주지는 않는다(2026-08-06).
   *
   * 화면이 바뀌는 것은 btns, 화면 안에서 끝나는 것은 acts 다.
   */
  acts?: [string, string][];
}
/**
 * 이 메뉴를 누가 쓰는가.
 *
 * 안 적으면 손님용으로 본다. 손님 메뉴와 운영자 메뉴가 한 헤더에 나란히 붙은
 * 사이트가 나와서 생긴 값이다 — 손님과 사장이 같은 화면을 쓰는 서비스는 없다.
 *   customer  손님(회원)이 쓰는 화면
 *   owner     매장·판매자·강사 등 운영하는 쪽이 쓰는 화면
 *   account   로그인·회원가입처럼 양쪽 공통이고 헤더 밖에 있는 화면
 */
export type Audience = "customer" | "owner" | "account";

export interface TplMenu {
  code: string;
  nameKo: string;
  nameEn: string;
  desc: string;
  /** 없으면 customer로 본다. */
  audience?: Audience;
  screens: TplScreen[];
}

