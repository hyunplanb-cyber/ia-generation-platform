//
//  ⛔ 주간 카드 파이프라인(_작업/영상굽기.mjs)의
//       _이미지/마스코트/영상/_편별.json · _최근.json  은 «읽기만» 한다.
//     릴스 편 이름을 써 넣으면 영상인트로.mjs 168줄이 그 줄을 그대로 믿어
//     주간 커버 누끼 짝짓기가 어긋난다.
//
//  릴스가 «쓰는» 곳은 둘뿐이다
//    <회차>/마스코트.txt            ← 세로판·가로판·다시굽기가 «같은» 것을 쓰게 한다
//    릴스영상/_마스코트_최근.json    ← 릴스끼리 안 겹치게
// ═══════════════════════════════════════════════════════════════════════════

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { 릴스방, 마스코트방, 마스코트방있나, 있는영상, 자리찾기 } from "./_마스코트.mjs";
import { 규격, 최소틈 } from "./_규격.mjs";

const 공유최근 = path.join(마스코트방, "_최근.json");   // ← 읽기만 한다
const 릴스최근길 = path.join(릴스방, "_마스코트_최근.json");

const 읽기 = (p) => { try { return JSON.parse(readFileSync(p, "utf8")); } catch { return {}; } };

/** 이 영상을 세로판 띠에 쓸 수 있나.
 *  ① 자리표의 띠쓰나 — 캐릭터가 화면 왼쪽~가운데면 제목 글자가 얼굴 위에 앉는다
 *  ② 제목 잉크 오른끝과 캐릭터 왼끝 사이가 최소틈(60px) 이상인가
 *
 *  ⚠ 잰것 === false (자리표에 없는 새 영상) 은 여기서 «된다»로 나올 수 있다.
 *     되돌이 값으로 잰 셈이라 믿을 수 없다 — 그래서 «자동 뽑기»에서는 마스코트고르기가
 *     따로 걸러 낸다. 손지정(--마스코트)일 때만 이 판정을 그대로 쓴다.
 *
 *  ⛔ 띠폭을 손으로 적지 않는다 — 규격["9_16"].띠.w 다. (2026-09-04 밤 · 신4②)
 *     마스코트자리.mjs 는 g.띠.w 로 제대로 읽는데 여기만 2160 을 베껴 두어,
 *     _규격.mjs 의 띠 폭을 고치면 둘이 다른 잣대로 재게 되어 있었다. */
export function 후보인가(파일, 제목오른끝, 띠폭 = 규격["9_16"].띠.w, 틈 = 최소틈) {
  const 자 = 자리찾기(파일);
  const 왼 = Math.round(자.x0 * 띠폭);
  const 남는틈 = 왼 - 제목오른끝;
  return { 된다: Boolean(자.띠쓰나) && 남는틈 >= 틈, 왼, 남는틈, 띠쓰나: Boolean(자.띠쓰나), 잰것: 자.잰것 };
}

/**
 * 고르는 차례 — 3단이다. 2단을 빼면 무작위가 된다.
 *   ① --마스코트 로 손지정
 *   ② <회차>/마스코트.txt 에 이미 적힌 것
 *   ③ 새로 뽑기   (후보 = 띠쓰나 true · 제목과 틈이 넉넉 · ⭐자리표에 «잰» 것)
 *        1단  후보 − 릴스최근 − 주간최근      둘 다 안 쓴 것
 *        2단  후보 − 릴스최근                릴스에서 안 쓴 것          ⛔ 빼면 안 된다
 *        3단  후보 전체                      한 바퀴 다 돌았다
 *
 * ⛔ 2단이 반드시 있어야 한다. 주간 _최근.json 에는 지금 10개가 들어 있다.
 *    그것을 1단과 같은 무게로 빼면 우리 후보 9개가 통째로 지워지고 순수 무작위가 된다
 *    (실제로 밟았다 — 강가가 세 편 내리 나왔다).
 *    릴스 제 최근이 «딱딱한 규칙», 주간 최근은 그 안에서의 «취향»이다.
 */
export function 마스코트고르기({ 회차, 지정, 제목오른끝 = 0 }) {
  const 회차방 = path.resolve(회차);
  const 장부 = path.join(회차방, "마스코트.txt");
  const 있는것 = 있는영상();
  if (있는것.length === 0) {
    // A2 — 여기서 멈추면 현님은 빠져나갈 길을 모르신다. 반드시 --띠없이 를 알려 드린다.
    throw new Error(
      (마스코트방있나()
        ? `마스코트 영상이 하나도 없습니다: ${마스코트방}`
        : `마스코트 영상 폴더가 없습니다: ${마스코트방}`) + "\n" +
      `  마스코트 없이 구우시려면:  node 영상만들기.mjs "${path.basename(회차방)}" --띠없이\n` +
      `  (제목 띠가 어두운 바탕색 그대로 나갑니다 — 틀 PNG 와 제목은 그대로 쓸 수 있습니다)`);
  }

  // ① 손지정
  if (지정) {
    const hit = 있는것.find((f) => f === 지정 || f === 지정 + ".mp4" || f.includes(지정));
    if (!hit) throw new Error(`마스코트를 못 찾았어요: ${지정}\n  있는 것: ${있는것.join(" / ")}`);
    mkdirSync(회차방, { recursive: true });
    writeFileSync(장부, hit + "\n", "utf8");
    return { 파일: hit, 어디서: "--마스코트 로 지정" };
  }

  // ② 이 회차에 이미 정해진 것 — 세로판·가로판을 따로 구워도 같은 것이 나오게 한다
  //    (2026-08-20 에 세로는 아침테라스·가로는 온천으로 나간 사고를 막는다)
  if (existsSync(장부)) {
    const 적힌것 = readFileSync(장부, "utf8").trim();
    if (있는것.includes(적힌것)) return { 파일: 적힌것, 어디서: "마스코트.txt (이 회차에 이미 정해짐)" };
    console.warn(`  ⚠ 마스코트.txt 에 적힌 «${적힌것}» 를 못 찾아 다시 뽑습니다.`);
  }

  // ③ 새로 뽑는다
  //  ⛔ 잰것 === false — 자리표에 없는 새 영상은 «자동 뽑기»에서 뺀다. (2026-09-04)
  //     되돌이(x0 0.680 · 머리 0.255 · 띠쓰나 true)로 후보가 되어, 잰 것들과 «같은 무게»로
  //     뽑혔다(40번 뽑아 1/10). 자르는 자리가 맞는지 아무도 모르는 채로 나간다.
  //     쓰시려면 node 마스코트자리.mjs 로 재서 표에 적으시거나 --마스코트 로 손지정하신다.
  const 판정 = new Map(있는것.map((f) => [f, 후보인가(f, 제목오른끝)]));
  const 자동된다 = (f) => 판정.get(f).된다 && 판정.get(f).잰것;
  const 후보 = 있는것.filter(자동된다);
  const 왜뺐나 = (f) => {
    const p = 판정.get(f);
    if (!p.잰것) return "자리표에 없음";
    if (!p.띠쓰나) return "띠쓰나 false";
    return `틈 ${p.남는틈}px`;
  };
  const 뺀것 = 있는것.filter((f) => !자동된다(f)).map((f) => `${f}(${왜뺐나(f)})`);
  const 표에없는것 = 있는것.filter((f) => !판정.get(f).잰것);

  if (후보.length === 0) {
    const 길이탓 = 있는것.some((f) => 판정.get(f).잰것 && 판정.get(f).띠쓰나);
    throw new Error(
      (길이탓
        ? `제목이 너무 길어 세로판 띠에 쓸 수 있는 마스코트가 없습니다 (제목 잉크 오른끝 x=${제목오른끝}).`
        : `세로판 띠에 쓸 수 있는 마스코트가 없습니다 (자리표에 «띠쓰나 true» 인 것이 하나도 없습니다).`) + "\n" +
      (길이탓 ? `  한 줄을 줄이시거나, ` : `  `) +
      `--마스코트 <파일> 로 직접 고르시거나, --띠없이 로 어두운 띠에 구우세요.\n` +
      (표에없는것.length
        ? `  자리표에 없는 것: ${표에없는것.join(" / ")}  → node 마스코트자리.mjs 로 재서 _마스코트자리.json 에 적어 주세요.\n`
        : "") +
      `  뺀 것: ${뺀것.join(" / ")}`);
  }
  if (표에없는것.length) {
    console.log(`  ⚠ 자리표(_마스코트자리.json)에 없어 자동 뽑기에서 뺐습니다: ${표에없는것.join(" / ")}`);
    console.log(`     node 마스코트자리.mjs 로 그림을 뽑아 재서 표에 적으시면 후보가 됩니다.`);
  }

  const 릴스최근 = new Set(읽기(릴스최근길).최근 || []);
  const 주간최근 = new Set(읽기(공유최근).최근 || []);
  let 풀 = 후보.filter((f) => !릴스최근.has(f) && !주간최근.has(f));   // 1단
  let 단 = 1;
  if (풀.length === 0) { 풀 = 후보.filter((f) => !릴스최근.has(f)); 단 = 2; }   // 2단
  if (풀.length === 0) { 풀 = 후보; 단 = 3; }                                   // 3단
  const 고른것 = 풀[Math.floor(Math.random() * 풀.length)];

  // 기록 — ⛔ 릴스 «자기» 파일에만 쓴다. 굽기를 죽이지 않게 삼킨다
  try {
    mkdirSync(회차방, { recursive: true });
    writeFileSync(장부, 고른것 + "\n", "utf8");
    const 이전 = 읽기(릴스최근길).최근 || [];
    // 기억은 후보수−1 만큼만. 다 기억하면 영영 못 뽑히는 것이 생긴다
    const 새최근 = [고른것, ...이전.filter((f) => f !== 고른것)].slice(0, Math.max(1, 후보.length - 1));
    writeFileSync(릴스최근길,
      JSON.stringify({ 갱신: new Date().toISOString(), 회차: path.basename(회차방), 최근: 새최근 }, null, 1) + "\n", "utf8");
  } catch (e) {
    console.warn(`  ⚠ 마스코트 기록을 못 남겼습니다 (굽기는 계속합니다): ${e.message}`);
  }

  return { 파일: 고른것, 어디서: `새로 뽑음 (${단}단)`, 후보, 뺀것 };
}
