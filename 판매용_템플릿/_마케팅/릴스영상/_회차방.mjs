/* 회차 폴더가 «어디 있나» — 한 곳에서 정한다.
 *
 * 왜 있나 (2026-09-10 현님 지시)
 *   회차 폴더가 릴스영상 바로 아래에 「2. 완성화면_…」·「3. 공동구매」·「9. 새틀시험」처럼
 *   놓여 있었다. 그 이름이 «{n}. {업종}» 꼴이라 팩 재료 도구가 세는 번호와 부딪혔다 —
 *   「9. 새틀시험」이 번호를 9까지 끌어올려 새 업종에 11번이 붙었고,
 *   「공동구매」를 부르면 2분할 회차 폴더 «안에» 팩 영상을 쏟아붓게 돼 있었다.
 *   → 회차는 `_회차/` 아래로 모은다. 그러면 「{n}. {업종}」은 업종만 센다.
 *
 *   그리고 회차 폴더는 «작업대»다 — 편수만큼 늘어나니 언젠가 통째로 지운다.
 *   그러려면 아무도 그 안을 남의 재료로 가리키면 안 된다.
 *   그 규칙은 `_작업/자막검사.mts` 가 굽기 전에 센다.
 *
 * 왜 네 도구가 같은 줄을 네 벌 갖고 있으면 안 되나
 *   틀그리기·마스터만들기·자막굽기·영상만들기가 모두 같은 후보 목록을 적어 두고 있었다.
 *   한 벌만 고치면 조용히 어긋난다 — 틀그리기는 새 자리에 만들고 자막굽기는 옛 자리를 찾는 식이다.
 *   그래서 여기 한 곳에 둔다.
 *
 * ⚠ 찾을 때는 «옛 자리도» 본다. 옮기다 만 것이 있어도 못 찾는 일이 없게.
 *   만들 때는 «늘 _회차 아래»에 만든다.
 */
import { existsSync } from "node:fs";
import path from "node:path";

/** 회차를 모아 두는 폴더 이름. */
export const 회차방이름 = "_회차";

/**
 * 이미 있는 회차 폴더를 찾는다. 못 찾으면 null.
 * @param {string} 여기   릴스영상 폴더의 절대 경로
 * @param {string} 회차   회차 이름(또는 경로)
 */
export function 회차방찾기(여기, 회차) {
  return [
    path.resolve(회차),                        // 절대경로거나 cwd 기준으로 주신 것
    path.resolve(여기, 회차방이름, 회차),       // 지금 자리
    path.resolve(여기, 회차),                  // 옛 자리 — 옮기다 만 것
  ].find(existsSync) ?? null;
}

/**
 * 회차 폴더로 «쓸» 길. 이미 있으면 그 자리, 없으면 앞으로 만들 자리(_회차 아래).
 * @param {string} 여기   릴스영상 폴더의 절대 경로
 * @param {string} 회차   회차 이름(또는 경로)
 */
export function 회차방길(여기, 회차) {
  if (path.isAbsolute(회차)) return path.resolve(회차);
  return 회차방찾기(여기, 회차) ?? path.resolve(여기, 회차방이름, 회차);
}
