function 그리기(판) {
  const g = 규격[판];
  const out = path.join(DIR, `${판}.png`);

  const boxes = [`drawbox=x=${g.영상.x}:y=${g.영상.y}:w=${g.영상.w}:h=${g.영상.h}:color=${브라우저색}@1:t=fill`];
  if (g.PiP) boxes.push(`drawbox=x=${g.PiP.x}:y=${g.PiP.y}:w=${g.PiP.w}:h=${g.PiP.h}:color=${PiP색}@1:t=fill`);

  const r = spawnSync("ffmpeg", [
    "-y", "-v", "error", "-f", "lavfi", "-i", `color=c=${바탕색}:s=${g.W}x${g.H}`,
    // format=rgb24 를 앞에 둔다 — 안 두면 yuv 를 거치며 46 이 45 로 어긋난다
    "-vf", `format=rgb24,${boxes.join(",")}`,
    "-frames:v", "1", out,
  ], { stdio: ["ignore", "pipe", "pipe"], encoding: "utf8" });
  if (r.status !== 0) { console.error(r.stderr?.slice(-1800)); process.exit(1); }

  console.log(`  ✔ ${판}.png  ${g.W} x ${g.H}`);
  console.log(`      브라우저 칸  ${g.영상.w} x ${g.영상.h}  (x=${g.영상.x} y=${g.영상.y})  rgb(46,46,46)`);
  if (g.PiP) console.log(`      코드창 PiP   ${g.PiP.w} x ${g.PiP.h}  (x=${g.PiP.x} y=${g.PiP.y})  rgb(64,64,64)`);
  console.log(`      마스코트 띠  ${g.띠.w} x ${g.띠.h}  (x=${g.띠.x} y=${g.띠.y})  ← 비워 둡니다. 영상이 덮습니다`);
}

