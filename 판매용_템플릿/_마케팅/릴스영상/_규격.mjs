export const 브라우저색 = "0x2E2E2E";   // rgb(46,46,46)
export const PiP색      = "0x404040";   // rgb(64,64,64)
export const 바탕색     = "0x1A1512";   // rgb(26,21,18) — 위 둘과 tol 3 안에서 절대 안 겹친다

/** "0x2E2E2E" → [46, 46, 46].
 *  틀그리기.mjs 는 drawbox 에 «글꼴 그대로» 넣고, 영상만들기.mjs 는 색을 «찾아야» 해서
 *  숫자 셋이 필요하다. 두 곳에 따로 적지 않도록 여기서 쪼갠다. (2026-09-04 밤 · 신4③) */
export const 색세개 = (s) => String(s).replace(/^0x/i, "").match(/../g).map((h) => parseInt(h, 16));

/** 제목 글자가 마스코트 얼굴 위에 앉지 않게 두는 최소 틈(px, 2160 기준).
 *  가이드가 둔 틈은 78px 이다. 60 은 그보다 조금 좁게 잡은 값. */
export const 최소틈 = 60;
