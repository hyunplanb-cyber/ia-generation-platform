/* 3뎁스 잎사귀를 그리는 공통 틀.
 *
 * 잎사귀는 2뎁스 화면의 «안»이다 — 탭을 눌렀을 때, 값이 모자랄 때, 아무것도 없을 때.
 * 그래서 세 가지가 늘 붙는다.
 *   ① 어느 화면의 안쪽인가 (빵부스러기)  ② 그 상태가 실제로 어떻게 보이나
 *   ③ 이 화면이 다루는 것 (만드는 사람이 놓치지 않게)
 *
 * ③을 붙이는 까닭 — 프리미엄을 사는 사람은 «이 화면을 왜 만들어야 하는지»를 알고 싶어 한다.
 * 정상 흐름은 누구나 그리지만, 「재고가 하루 모자랄 때」는 시키지 않으면 아무도 안 만든다.
 */
import * as U from './ui.mjs';

/** 어느 화면의 안쪽인지 — 3뎁스는 이게 없으면 길을 잃는다 */
export const crumb = (부모id, 부모이름) => `<nav class="crumb" aria-label="위치">
  <a href="${U.link('HO0101')}">홈</a><span class="sep">›</span>
  <a href="${U.link(부모id)}">${부모이름}</a><span class="sep">›</span>
  <span>안쪽 화면</span></nav>`;

/**
 * 잎사귀 한 장.
 *   부모: [화면id, 화면이름]
 *   제목·설명: 이 상태가 무엇인지
 *   본문: 그 상태를 실제로 그린 것
 *   다루는것: [[무엇, 어떻게], …] — 만드는 사람에게 주는 표
 */
export const 잎 = ({ 부모, 제목, 설명, 본문, 다루는것, o = {} }) => ({
  o,
  body: `${crumb(부모[0], 부모[1])}
${U.pageHd(제목, 설명)}
${본문}
${다루는것 ? U.card('이 화면이 다루는 것', U.kv(다루는것), { cls: 'mt8' }) : ''}
<div class="btns mt6">${U.btn(`‹ ${부모[1]}로 돌아가기`, { href: 부모[0] })}</div>`,
});
