/** 화면에 보일 상태 — 지킴이가 «막혀» 있으면 그 사실이 상태보다 먼저다.
 *
 * ⛔ 왜 필요한가 (2026-08-26 사장님: 「제작중이라고 하는데 반영을 안 하고 계속 제작중이야」)
 *   「제작중」의 풀이는 「다시 만들고 있습니다. 끝나면 검토대기로 돌아옵니다」이다.
 *   그런데 지킴이가 막혀 있으면 **아무도 안 만들고 있고, 사람이 손대기 전에는 영영
 *   안 돌아온다.** 화면이 거짓말을 하고 있었던 것이다 — 기다리면 될 줄 알고 기다리게 된다.
 *   막힌 까닭(watcherError)이 있으면 이름과 풀이를 «막힘»으로 바꾼다.
 *
 * ⚠ 상태값 자체는 안 건드린다. 지킴이는 손본 뒤 그대로 다시 집어야 하므로 approved 는
 *   approved 로 남아야 한다. 바뀌는 것은 «사람에게 보이는 말»뿐이다.
 */
export const 상태보기 = (s: string, 막힌까닭?: string | null) => {
  const 바탕 = 상태말[s] ?? 상태말.waiting;
  if (!막힌까닭 || !막힌까닭.trim()) return 바탕;
  return {
    글: `${바탕.글} · 막힘`,
    반: "bg-rose-100 text-rose-900",
    풀이: "지킴이가 여기서 멈췄습니다. 아래 까닭을 풀어 주기 전에는 저절로 다음으로 가지 않습니다.",
  };
};

/** 이름표에서 «영상 번호»만 뽑는다 — `영상22_색이달라지는거` → `22`.
 *
 * ⛔ 왜 있나 (2026-09-02 사장님: 「영상 번호 검수기 리스트에서도 확인할 수 있게 해줘」)
 *   목록에 있던 것은 상태·회차·슬롯·제목뿐이었다. 그런데 사장님과 제가 편을 부르는 이름은
 *   «영상 22» 다 — 대본도 `대본_…`, 구운 파일도 `영상22_…`, 검수기 상세 화면도 이름표를
 *   그대로 보여 준다. 목록에서만 번호가 빠져 있어서, 「영상 22 어디 갔지」를 제목으로
 *   되짚어야 했다.
 *
 * ⚠ 번호가 없는 편이 실제로 있다 — `펫유치원_컷편집`. 그때는 null 을 준다.
 *   부르는 쪽이 이름표를 그대로 보여 주면 된다. **없는 번호를 지어내지 않는다.**
 */
export const 영상번호 = (이름표: string): string | null => {
  const 잡힌것 = /^영상\s*(\d+)/.exec((이름표 ?? "").trim());
  return 잡힌것 ? 잡힌것[1] : null;
};
