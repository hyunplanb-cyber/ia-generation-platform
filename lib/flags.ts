// 아직 열지 않은 기능의 스위치.

/**
 * 요금제 화면을 여는가.
 *
 * 결제 수단(PG)이 붙기 전까지는 닫아둔다 — 살 수 없는 요금제를 보여주면
 * 사용자는 갈 곳이 없고, 우리는 지키지 못할 약속을 하게 된다.
 * 결제를 붙일 때 이 값을 true 로 바꾸면 요금제 화면과 다운로드 안내가 함께 열린다.
 */
export const BILLING_OPEN = false;

/**
 * 크레딧 충전(토스 결제)을 여는가.
 *
 * 결제 연동은 붙였지만, 검증 전까지 기본은 닫아둔다(충전 페이지에 들어와도 대시보드로 보냄).
 * Vercel 환경변수 `CREDITS_OPEN=true` 로 켜서 테스트하고, 준비되면 유지한다.
 * (테스트 키가 들어간 상태라, 켜도 실제 결제는 되지 않고 테스트 모드로만 동작한다.)
 */
export const CREDITS_OPEN = process.env.CREDITS_OPEN === "true";

/**
 * AI팩 판매가를 손님에게 보여주는가.
 *
 * 아직 살 수 있는 길이 없어서(크몽 미등록·PG 전) 값을 먼저 내걸지 않는다.
 * 값만 보이고 살 수 없으면 "비싸다"는 인상만 남고 돌아가기 때문이다.
 * 판매를 열 때 이 값을 true로 바꾸면 목록·상세·랜딩의 가격이 한 번에 나타난다.
 */
export const PACKAGE_PRICES_PUBLIC = false;

/**
 * 화면 목록에서 화면을 직접 고칠 수 있게 하는가.
 *
 * 화면명·기능정의·프롬프트를 손으로 고치는 기능인데, 잘 쓰려면 기획 감각이 필요해
 * 대부분의 사용자에게는 부담이었다(2026-08-03 보류). 우리가 주는 건 "이대로 만들면
 * 되는 한 벌"이고, 그 뒤에 더 필요한 화면은 각자 쓰는 AI 도구나 개발사와 만드는 게 맞다.
 * 기능은 그대로 두고 버튼만 감춘다 — 다시 열 때 이 값만 true로 바꾸면 된다.
 */
export const SCREEN_EDIT_OPEN = false;

/**
 * AI팩을 우리 사이트에서 직접 살 수 있게 하는가.
 *
 * "구매하기 → 결제 → 바로 다운로드"까지 뒤쪽은 다 만들어 두고, 화면에서만 막는다.
 * PG 승인이 1~2달 걸리는 동안 버튼을 열어두면 살 수 없는 값만 보이기 때문이다.
 * 승인이 나면 이 값을 true로 바꾸는 것만으로 판매가 열린다.
 *
 * 크몽은 별개 판로다 — 수수료 때문에 값이 다를 수 있고, 승인도 우리 손 밖이다.
 * 크몽 링크(kmongUrl)가 있으면 그건 그것대로 함께 노출한다.
 */
export const PACKAGE_SALE_OPEN = process.env.PACKAGE_SALE_OPEN === "true";
