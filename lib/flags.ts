/**
 * 요금제 화면을 여는가.
 *
 * 결제 수단(PG)이 붙기 전까지는 닫아둔다 — 살 수 없는 요금제를 보여주면
 * 사용자는 갈 곳이 없고, 우리는 지키지 못할 약속을 하게 된다.
 * 결제를 붙일 때 이 값을 true 로 바꾸면 요금제 화면과 다운로드 안내가 함께 열린다.
 */
export const BILLING_OPEN = false;

/**
 * 크레딧 충전(토스 결제)을 여는가.
 *
 * 결제 연동은 붙였지만, 검증 전까지 기본은 닫아둔다(충전 페이지에 들어와도 대시보드로 보냄).
 * Vercel 환경변수 `CREDITS_OPEN=true` 로 켜서 테스트하고, 준비되면 유지한다.
 * (테스트 키가 들어간 상태라, 켜도 실제 결제는 되지 않고 테스트 모드로만 동작한다.)
 */
export const CREDITS_OPEN = process.env.CREDITS_OPEN === "true";

/**
 * 결제를 «이 계정들에만» 여는 문 — 카드사 심사 기간에 쓴다.
 *
 * 왜 필요한가 (2026-08-09)
 *   카드사 심사는 테스트 키로 받아도 된다(토스 결제경로 가이드 유의사항 6번).
 *   그런데 테스트 키는 **돈을 안 받고도 「결제 성공」이라고 답한다.**
 *   그 상태로 결제를 전체 공개하면, 아무나 공짜로 크레딧을 받아 생성·다운로드를 한다.
 *   크레딧 자체는 우리 DB 숫자라 0원이지만 **생성·다운로드는 진짜 돈이 나간다** —
 *   10만원치(1,300크레딧)를 기본 생성에 다 쓰면 108번, 43,200원이다. 횟수 제한도 없다.
 *
 *   금액을 낮추는 걸로는 못 막는다. 얼마짜리든 손님 눈에 결제창이 뜨면
 *   「결제됐는데 카드에서 안 빠지는」 일이 생기고, 그건 설명할 방법이 없다.
 *
 *   토스 계약과정 FAQ 10번이 길을 열어 뒀다 —
 *   「비회원으로 접근했을 때도 확인할 수 있게 설정해주시거나,
 *     **심사관이 확인할 수 있는 테스트 계정(아이디/비밀번호)을 전달**해주셔야 해요.」
 *   둘 중 하나면 된다. 그래서 심사관 계정에만 연다. 노출 금액이 0이 된다.
 *
 * 쓰는 법: Vercel 환경변수에 쉼표로 이메일을 적는다.
 *   BILLING_ALLOWLIST=심사용계정@example.com,우리계정@example.com
 * 심사가 끝나면 CREDITS_OPEN=true 로 바꾸고 이 값은 비운다.
 *
 * ⚠ 계약담당자에게 **「결제 확인은 전달드린 테스트 계정으로 로그인 후 부탁드립니다」**
 *   를 반드시 함께 전하세요. 안 그러면 심사관이 비회원으로 눌러 보고
 *   「결제창이 확인되지 않는다」로 반려합니다(FAQ 10번).
 */
const BILLING_ALLOWLIST = (process.env.BILLING_ALLOWLIST ?? "")
  .split(",")
  .map((s) => s.trim().toLowerCase())
  .filter(Boolean);

/** 이 사람에게 결제(충전·팩 구매)를 열어도 되나. */
export function billingOpenFor(email: string | null | undefined): boolean {
  if (CREDITS_OPEN) return true; // 전체 공개된 상태
  if (!email) return false;
  return BILLING_ALLOWLIST.includes(email.toLowerCase());
}

/**
 * 카드사 심사 모드 — 심사 기간에만 켠다(`REVIEW_MODE=true`).
 *
 * 테스트 키로 심사를 받는 동안 **우리가 얼마를 잃을 수 있는지 모르는 상태**가 된다.
 * 심사관이 몇 번 어떻게 눌러볼지 알 수 없고, 다운로드는 한 번 나가면 되돌릴 수 없다.
 * 그래서 「설마 많이 하겠어」로 두지 않고 **최악을 숫자로 못 박는다.**
 *
 * 켜면 이렇게 된다
 *   · 오푸스 보강을 건너뛴다        다운로드 1건 3,000~10,000원 → 0원
 *   · 충전은 계정당 REVIEW_MAX_CHARGES 회까지
 *   · 팩은 REVIEW_OPEN_PLAN 등급만 살 수 있다 (나머지는 「준비 중」)
 *
 * 심사가 끝나면 이 값을 지우고 CREDITS_OPEN=true 로 바꾼다.
 * 그때 **테스트 기간에 지급된 크레딧을 정리하는 것**도 잊지 말 것 —
 * 그대로 두면 공짜 크레딧이 라이브에서 오푸스를 태운다.
 */
export const REVIEW_MODE = process.env.REVIEW_MODE === "true";

/** 심사 기간, 계정 하나가 충전할 수 있는 횟수. */
export const REVIEW_MAX_CHARGES = 2; // 5만원 × 2회 = 1,100크레딧(보너스 10%). 심사관이 팩+검수를 다 해봐도 남는다.

/** 심사 기간에 «실제로 결제되는» 충전 금액 — 이 한 칸만 열린다.
 *
 * 횟수만 막고 금액을 안 막았더니 구멍이 남아 있었다.
 * 9만 9천원을 두 번 고르면 2,178크레딧 — **22만원어치**가 나간다.
 * 계획은 5만원 두 번(1,100크레딧)이었으니 두 배다.
 *
 * 나머지 칸은 감추지 않고 「결제 심사중」으로 둔다. 감추면 라인업이 한 칸짜리로
 * 보여 「옵션 선택형」(가이드 유의사항 3)이 약해지고, 심사관도 우리가 팔려는
 * 구성을 못 본다. 보여주되 누르지 못하게 하는 쪽이 둘 다 만족한다. */
export const REVIEW_CHARGE_WON = 50000;

/** 심사 기간에 이 금액을 실제로 충전할 수 있나. */
export function chargeableNow(priceKrw: number): boolean {
  return REVIEW_MODE ? priceKrw === REVIEW_CHARGE_WON : true;
}

/** 심사 기간에 살 수 있게 열어 둘 등급.
 *
 * 플러스인 까닭 — 503크레딧이라 **한 번 충전(5만원 = 650)에 여유 있게 닿는다.**
 * 심사 모드는 보너스가 10%라 5만원이 550크레딧이고, 그것으로도 덮인다.
 * 등급 하나를 열면 업종마다 하나씩 열리므로 「카테고리마다 최소 1개」도 채운다. */
export const REVIEW_OPEN_PLAN = "plus";

/** 심사 기간에 이 등급을 살 수 있나. */
export function planBuyableNow(planId: string): boolean {
  return REVIEW_MODE ? planId === REVIEW_OPEN_PLAN : true;
}

