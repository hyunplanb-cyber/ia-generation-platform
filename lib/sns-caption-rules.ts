export type 대본 = {
  이름?: string;
  세로제목?: string;
  가로제목?: string;
  칸초?: number;
  칸들?: 대본칸[];
};

const 벗기기 = (s: unknown) => String(s ?? "").replace(/<[^>]*>/g, "");
const 낱말들 = (s: unknown) =>
  벗기기(s).replace(/[^가-힣A-Za-z0-9 ]/g, " ").split(/\s+/).filter((w) => w.length >= 2);

/** 자막 글자 수 — 공백과 표시(span)를 뺀 것. 300~360 이 목표다. */
export function countLetters(칸들: 대본칸[]): number {
  return 벗기기(칸들.map((k) => (k.cap ?? []).join(" ")).join(" ")).replace(/\s/g, "").length;
}

/**
 * 대본 한 편을 검사한다. `별명` 은 포즈 별명표(부르는 이름 → 실제 파일).
 * 프레임(화면)과 자막이 맞는지는 «사람만» 볼 수 있다 — 그건 `/admin/sns` 의 몫이다.
 */
export function checkScript(편: 대본, 별명: Map<string, string> = new Map()): 걸린것[] {
  const 걸림: 걸린것[] = [];
  const 칸들 = 편.칸들 ?? [];
  const 칸초 = 편.칸초 ?? 2.5;
  const 자막글 = 칸들.map((k) => (k.cap ?? []).join(" ")).join(" ");
  const 표지글 = [편.세로제목, 편.가로제목].map(벗기기).join(" ");
  const 온글 = 벗기기(`${표지글} ${자막글}`);

  const 떼목록: [규칙[], string][] = [
    [금지어, "금지어"],
    [경력자랑, "경력 자랑"],
    [틀린상대, "견주는 상대"],
    [자책, "서비스 흠"],
  ];
  for (const [떼, 이름표] of 떼목록) {
    for (const 규칙 of 떼) {
      const 찾음 = 온글.match(new RegExp(규칙.말, "g"));
      if (!찾음) continue;
      const 자리: string[] = [];
      칸들.forEach((k, i) => {
        if (규칙.말.test(벗기기((k.cap ?? []).join(" ")))) 자리.push(`${i + 1}번 칸`);
      });
      if (규칙.말.test(벗기기(표지글))) 자리.unshift("표지·제목");
      걸림.push({
        어디: 이름표,
        무엇: `「${[...new Set(찾음)].join("」·「")}」 (${자리.join(", ") || "?"})`,
        대신: 규칙.대신,
        왜: 규칙.왜,
        칸: 칸들.findIndex((k) => 규칙.말.test(벗기기((k.cap ?? []).join(" ")))) + 1 || undefined,
      });
    }
  }

  const 글자수 = countLetters(칸들);
  if (글자수 < 290 || 글자수 > 370)
    걸림.push({ 어디: "자막 분량", 무엇: `공백 제외 ${글자수}자`, 대신: "300~360자", 왜: "적으면 빈 영상, 많으면 못 읽는다 (8/13)" });

  const 길이 = +(칸들.length * 칸초).toFixed(1);
  if (길이 < 25 || 길이 > 40)
    걸림.push({ 어디: "길이", 무엇: `${칸들.length}칸 × ${칸초}초 = ${길이}초`, 대신: "25~40초", 왜: "길수록 유지율이 떨어진다 (실측)" });

  const 초당 = 길이 ? +(글자수 / 길이).toFixed(1) : 0;
  if (초당 > 12)
    걸림.push({ 어디: "읽는 속도", 무엇: `초당 ${초당}자`, 대신: "12자 이하", 왜: "글자를 줄이거나 길이를 늘린다" });

  const 설명체 = 칸들.filter((k) => /(합니다|입니다)[.!?]?\s*$/.test(벗기기((k.cap ?? []).join(" ")).trim())).length;
  if (칸들.length && 설명체 / 칸들.length > 0.5)
    걸림.push({ 어디: "말투", 무엇: `${칸들.length}칸 중 ${설명체}칸이 「~합니다」`, 대신: "절반 아래로", 왜: "겪은 일은 「~더라고요」로" });

  const 제목말 = new Set(낱말들(편.세로제목 ?? 편.가로제목 ?? ""));
  const 겹침 = 낱말들((칸들[0]?.cap ?? []).join(" ")).filter((w) => 제목말.has(w));
  if (겹침.length >= 3)
    걸림.push({ 어디: "첫 자막", 무엇: `제목과 「${겹침.join("·")}」가 겹친다`, 대신: "이미 벌어진 «장면»으로 연다", 왜: "제일 비싼 3초를 같은 말 두 번에 쓴다", 칸: 1 });

  /* ⭐ 화면 잘림 — 2026-08-17 사고. 사장님: 「이 부분은 여러번 체크했던건데.」 */
  const 컷들 = 칸들.flatMap((k) => k.shots ?? []);
  const 당김수 = 컷들.filter((s) => s.당김).length;
  if (당김수 > 1)
    걸림.push({
      어디: "화면 잘림",
      무엇: `"당김": true 가 ${당김수}곳`,
      대신: "한 편에 최대 1곳. 잘림 경고를 끄려고 쓴 것이면 zoom 을 1.0 으로",
      왜: "당김은 «일부러 파고드는 컷» 하나를 면제하는 값이다 (8/17 사고)",
    });
  const zoom없음 = 컷들.filter((s) => s.clip && s.zoom == null).length;
  if (zoom없음)
    걸림.push({
      어디: "화면 잘림",
      무엇: `녹화 컷 ${zoom없음}곳에 zoom 이 없다`,
      대신: "clip 컷마다 zoom 을 적는다. 가로로 꽉 찬 화면이면 1.0",
      왜: "기본값에 맡기면 넓은 PC 화면이 좌우로 잘린다 (8/17 사고)",
    });

  칸들.forEach((k, i) => {
    const n = (k.shots ?? []).length;
    if (n && ![1, 2, 3, 6].includes(n))
      걸림.push({ 어디: "컷 수", 무엇: `${i + 1}번 칸에 컷 ${n}개`, 대신: "1·2·3·6 개만", 왜: "다른 수는 굽다가 멈춘다", 칸: i + 1 });
  });

  /* 포즈는 «별명표를 거친 실제 파일»로 견준다 — 겉이름만 보면 안 잡힌다(8/17 사고). */
  const 실제포즈 = 칸들.filter((k) => k.pose).map((k) => 별명.get(k.pose!) ?? k.pose!);
  const 두번 = 실제포즈.filter((p, i) => 실제포즈.indexOf(p) !== i);
  if (두번.length)
    걸림.push({ 어디: "고양이 포즈", 무엇: `「${[...new Set(두번)].join("」·「")}」가 두 번`, 대신: "한 편에 같은 포즈를 두 번 쓰지 않는다", 왜: "별명표를 거친 실제 파일로 견준다" });
  /* 마무리 CTA 두 칸은 화면 없이 고양이만 나오므로 늘 포즈를 물고 있다 — 본문만 센다. */
  const 본문포즈 = 칸들.filter((k) => k.pose && (k.shots ?? []).length).length;
  if (본문포즈 < 3 || 본문포즈 > 5)
    걸림.push({ 어디: "고양이 포즈", 무엇: `본문에 ${본문포즈}번`, 대신: "본문에 3~5번", 왜: "마무리 CTA 칸은 세지 않는다" });

  const 끝 = (칸들.at(-1)?.cap ?? []).map(벗기기).join(" ");
  if (!끝.includes("캡션") || !끝.includes("링크"))
    걸림.push({ 어디: "마무리", 무엇: `「${끝}」`, 대신: "「AI팩이 궁금하시다면,」 / 「캡션과 프로필 링크를 확인해 주세요.」", 왜: "마지막 칸은 고정이다", 칸: 칸들.length });

  const 색칸 = 칸들.filter((k) => /<span class='[ot]'>/.test((k.cap ?? []).join(""))).length;
  if (색칸 < 3)
    걸림.push({ 어디: "포인트 색", 무엇: `${색칸}칸만 색이 있다`, 대신: "숫자·핵심어에 주황(o)·틸(t)을 3~6칸", 왜: "온통 검정이면 어디를 볼지 모른다 (8/12)" });

  return 걸림;
}

